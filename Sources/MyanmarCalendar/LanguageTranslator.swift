struct LanguageTranslator {

    /// Translate a number to the specified language
    static func translate(_ value: Int, _ language: Language) -> String {
        let str = String(value)
        if language == .english {
            return str
        }
        // For Myanmar numerals
        return translateDigits(str, language)
    }

    /// Translate digits to target language
    private static func translateDigits(_ input: String, _ language: Language) -> String {
        guard language != .english else { return input }

        var result = input
        // Myanmar/Zawgyi/Mon digits
        let digitMap: [Character: String] = [
            "0": "၀", "1": "၁", "2": "၂", "3": "၃", "4": "၄",
            "5": "၅", "6": "၆", "7": "၇", "8": "၈", "9": "၉"
        ]

        for (english, myanmar) in digitMap {
            result = result.replacingOccurrences(of: String(english), with: myanmar)
        }

        return result
    }

